def overlay_svg(asset_id: str) -> bytes:
    title, cue, body = OVERLAYS[asset_id]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="128" height="128">\n'
            f'  <!-- KidQuest shared overlay: {title}. Non-colour cue: {cue}. -->{body}\n</svg>\n').encode()


# --------------------------------------------------------------------------- main

def sha(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def build(write: bool) -> list[str]:
    themes, roads = load_content()
    ids = golden_ids(themes, roads)
    theme_ids = [t["id"] for t in themes["themes"]]
    differences: list[str] = []
    records = []

    def emit(path: Path, data: bytes) -> None:
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            differences.append(str(path.relative_to(REPO)))

    for theme in theme_ids:
        manifest_path = STATIC / "themes" / theme / "manifest.json"
        later_entries = []
        if manifest_path.is_file():
            later_entries = [entry for entry in json.loads(manifest_path.read_text()).get("assets", [])
                             if entry.get("source", {}).get("record_id", "").startswith("kq029/")]
        images = render_theme(theme, ids)
        entries = []
        for group, asset_id in ids:
            s = spec(group, asset_id)
            data = encode(images[asset_id], s["alpha_required"])
            rel = runtime_path(themes, theme, group, asset_id)
            emit(REPO / rel, data)
            record_id = f"kq006/{theme}/{asset_id}"
            entry = {"asset_id": asset_id, "category": s["category"], "content_version": themes["content_version"],
                     "required_in_themes": theme_ids, "runtime_path": rel, "fallback_path": None,
                     "pixel_size": s["pixel_size"], "css_cell_size": s["css_cell_size"]}
            for key in ("footprint", "anchor", "overhang", "collision_ref", "entrances"):
                if s[key] is not None:
                    entry[key] = s[key]
            entry.update({"layer": s["layer"], "z_offset": s["z_offset"], "alpha_required": s["alpha_required"],
                          "max_bytes": s["max_bytes"], "export_profile": s["export_profile"],
                          "source": {"record_id": record_id, "creator": GENERATOR, "license_status": LICENSE,
                                     "review_status": "in_review", "checksum": sha(data)},
                          "accessible_label_key": s["accessible_label_key"], "decorative": s["decorative"]})
            entries.append(entry)
            records.append({"record_id": record_id, "theme_id": theme, "asset_id": asset_id, "group": group,
                            "runtime_path": rel, "bytes": len(data)})
        manifest = {"manifest_version": themes["manifest_version"], "content_version": themes["content_version"],
                    "theme_id": theme,
                    "profile": "kq006_golden+kq029_buildings" if later_entries else "kq006_golden",
                    "note": ("KQ-006 golden non-building references plus KQ-029 lossless building extracts. "
                             "Art and cultural review remain pending; this is not a release manifest.") if later_entries else
                            "KQ-006 golden non-building reference set. Generated art pending art and cultural review; not a release manifest.",
                    "assets": entries + later_entries}
        emit(manifest_path, (json.dumps(manifest, indent=2) + "\n").encode())

    shared = []
    for asset_id, (title, cue, _body) in OVERLAYS.items():
        data = overlay_svg(asset_id)
        rel = f"static/images/kidquest/shared/overlays/{asset_id}.svg"
        emit(REPO / rel, data)
        record_id = f"kq006/shared/{asset_id}"
        shared.append({"asset_id": asset_id, "category": "overlay", "content_version": themes["content_version"],
                       "runtime_path": rel, "view_box": [0, 0, 128, 128], "css_cell_size": {"width": 64, "height": 64},
                       "layer": "interaction_overlays", "max_bytes": 4096, "meaning": title, "non_color_cue": cue,
                       "source": {"record_id": record_id, "creator": GENERATOR, "license_status": LICENSE,
                                  "review_status": "in_review", "checksum": sha(data)},
                       "decorative": True})
        records.append({"record_id": record_id, "theme_id": None, "asset_id": asset_id, "group": "shared_overlays",
                        "runtime_path": rel, "bytes": len(data)})
    shared_manifest = {"manifest_version": themes["manifest_version"], "content_version": themes["content_version"],
                       "scope": "shared",
                       "note": "Theme-independent semantic overlays (pipeline 11.2). The state is also given as HTML text; never colour alone.",
                       "assets": shared}
    emit(STATIC / "shared" / "manifest.json", (json.dumps(shared_manifest, indent=2) + "\n").encode())

    later_records = []
    if SOURCE_METADATA.is_file():
        later_records = [record for record in json.loads(SOURCE_METADATA.read_text()).get("records", [])
                         if record.get("record_id", "").startswith("kq029/")]
    metadata = {
        "schema": "kidquest-source-metadata/1",
        "description": "Source, ownership and review record for every KidQuest runtime asset (pipeline 14.1, 14.3). "
                       "Manifests reference these records by source.record_id. assets.schema.json only allows "
                       "review_status placeholder|graybox|in_review|approved, so the manifests say in_review and the "
                       "detailed review state lives here.",
        "generator": {"path": GENERATOR, "library": "design/kidquest/tools/kq_art.py", "version": GENERATOR_VERSION,
                      "command": f"python {GENERATOR}", "requires": "pip install -r requirements-assets.txt (Pillow 10.4.0 wheel with libwebp 1.4.0, numpy 1.26.4)",
                      "reproducibility": "Deterministic: seeded by sha256('kq006:{theme}:{purpose}'), no timestamps. "
                                         "Byte-identical with the same Pillow/libwebp; `--check` reports any drift."},
        "defaults": {
            "creator": GENERATOR, "license_status": LICENSE, "owner": "KidQuest project",
            "production_status": "golden_reference_candidate",
            "reviews": {"art": "pending_art_review", "cultural": "pending_cultural_review",
                        "accessibility_overlay_contrast": "pending_review", "geometry": "automated: scripts/validate_kidquest_assets.py",
                        "child_usability": "not_tested"},
        },
        "records": records + later_records,
        "graybox": {
            "path": "design/kidquest/templates/graybox-buildings/",
            "production_status": "graybox_non_production",
            "note": "Neutral building study that proves footprint/anchor/entrance rules for KQ-025. Never shipped; "
                    "not under static/images/kidquest/themes/*/buildings/ (owned by KQ-029).",
        },
    }
    meta_bytes = (json.dumps(metadata, indent=2) + "\n").encode()
    emit(SOURCE_METADATA, meta_bytes)
    return differences


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="regenerate in memory and compare with the committed files")
    args = parser.parse_args(argv)
    diffs = build(write=not args.check)
    if args.check:
        if diffs:
            print(f"{len(diffs)} file(s) differ from a fresh generation (different Pillow/libwebp, or stale exports):")
            for d in diffs:
                print(f"  - {d}")
            return 1
        print("Golden set is reproducible: every file matches a fresh generation byte for byte.")
        return 0
    print("Generated golden set, manifests, shared overlays and source metadata.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
