#!/usr/bin/env python3
"""Generate the KidQuest KQ-006 golden non-building asset set, manifests and source records.

Usage (from the repository root, in a venv with `pip install -r requirements-assets.txt`):
    python design/kidquest/tools/generate_golden_assets.py            # write everything
    python design/kidquest/tools/generate_golden_assets.py --check    # regenerate in memory, compare bytes

Writes, for each theme in content/kidquest/themes.json:
    static/images/kidquest/themes/{theme}/{terrain,roads,props,icons}/{asset_id}@2x.webp
    static/images/kidquest/themes/{theme}/manifest.json
and the shared, theme-independent overlays:
    static/images/kidquest/shared/overlays/overlay_*--*.svg
    static/images/kidquest/shared/manifest.json
plus design/kidquest/source-metadata.json (source, licence and review records).

The art is programmatic, generated by this script and owned by the project. It is a golden
REFERENCE CANDIDATE: art review and cultural review have NOT happened, so every record says so.
content/kidquest/ is read-only input; nothing there is written.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import kq_art as art  # noqa: E402
from PIL import Image  # noqa: E402

REPO = HERE.parents[2]
CONTENT = REPO / "content" / "kidquest"
STATIC = REPO / "static" / "images" / "kidquest"
SOURCE_METADATA = REPO / "design" / "kidquest" / "source-metadata.json"
GENERATOR = "design/kidquest/tools/generate_golden_assets.py"
GENERATOR_VERSION = 1
LICENSE = "generated by script, owned by the project"
WEBP_QUALITY = 88

# KQ-006 golden non-building set (plan section 7A M3A, pipeline Stage G). Groups are themes.json
# `runtime_assets.directories` keys; "all" means every entry roads.json derives for that group.
GOLDEN = {
    "terrain": ["ground_buildable--base", "water--base"],
    "shore_masks": "all",
    "road_masks": "all",
    "fixed_features": ["quest_board--base"],
    "icons": ["wood--icon"],
    "theme_selector": ["theme_thumbnail--base"],
}


def load_content():
    themes = json.loads((CONTENT / "themes.json").read_text())
    roads = json.loads((CONTENT / "roads.json").read_text())
    return themes, roads


def golden_ids(themes: dict, roads: dict) -> list[tuple[str, str]]:
    out = []
    for group, ids in GOLDEN.items():
        if ids == "all":
            ids = [m["asset_id"] for m in roads[group]]
        out += [(group, asset_id) for asset_id in ids]
    return out


def runtime_path(themes: dict, theme: str, group: str, asset_id: str) -> str:
    rule = themes["runtime_assets"]
    path = rule["path_template"].format(theme_id=theme, directory=rule["directories"][group], asset_id=asset_id)
    return path.lstrip("/")


def spec(group: str, asset_id: str) -> dict:
    """Manifest fields that depend only on the logical asset (identical in every theme)."""
    tile = {"pixel_size": {"width": 128, "height": 128}, "css_cell_size": {"width": 64, "height": 64},
            "footprint": {"width": 1, "height": 1}, "anchor": None, "overhang": None, "collision_ref": None,
            "entrances": None, "z_offset": 0, "max_bytes": 32 * 1024, "accessible_label_key": None, "decorative": True}
    if group == "terrain":
        water = asset_id.startswith("water")
        return {**tile, "category": "terrain", "layer": "water_shore" if water else "terrain", "alpha_required": False,
                "export_profile": f"webp_lossy_q{WEBP_QUALITY}_opaque",
                "collision_ref": "layouts/pulau_tunas_v1.json#water" if water else None}
    if group == "shore_masks":
        return {**tile, "category": "shore", "layer": "water_shore", "alpha_required": False,
                "export_profile": f"webp_lossy_q{WEBP_QUALITY}_opaque", "collision_ref": "layouts/pulau_tunas_v1.json#water"}
    if group == "road_masks":
        return {**tile, "category": "road", "layer": "paths", "alpha_required": True,
                "export_profile": f"webp_lossy_q{WEBP_QUALITY}_alpha_lossless", "collision_ref": "roads.json#road_masks"}
    if asset_id == "quest_board--base":
        return {**tile, "category": "fixed_feature", "layer": "props", "alpha_required": True,
                "pixel_size": {"width": 128, "height": 192}, "css_cell_size": {"width": 64, "height": 96},
                "anchor": {"x": 0.5, "y": 1}, "overhang": {"top": 0.5, "left": 0, "right": 0},
                "collision_ref": "layouts/pulau_tunas_v1.json#quest_board", "entrances": ["N", "E", "S", "W"],
                "max_bytes": 48 * 1024, "export_profile": f"webp_lossy_q{WEBP_QUALITY}_alpha_lossless",
                "accessible_label_key": "themes.labels.quest_board", "decorative": False}
    if asset_id == "wood--icon":
        return {**tile, "category": "icon", "layer": "props", "alpha_required": True,
                "pixel_size": {"width": 96, "height": 96}, "css_cell_size": {"width": 48, "height": 48},
                "footprint": None, "max_bytes": 16 * 1024, "export_profile": f"webp_lossy_q{WEBP_QUALITY}_alpha_lossless"}
    if asset_id == "theme_thumbnail--base":
        return {**tile, "category": "theme_selector", "layer": "props", "alpha_required": True,
                "pixel_size": {"width": 256, "height": 256}, "css_cell_size": {"width": 128, "height": 128},
                "footprint": None, "max_bytes": 60 * 1024, "export_profile": f"webp_lossy_q{WEBP_QUALITY}_alpha_lossless"}
    raise ValueError(f"no spec for {group}/{asset_id}")


def mask_of(asset_id: str) -> int:
    return int(asset_id.rsplit("_", 1)[1])


def thumbnail(theme: str, tiles: dict[str, Image.Image]) -> Image.Image:
    """Theme selector thumbnail composed from the theme's own golden assets (pipeline 12)."""
    scene = Image.new("RGBA", (384, 384), (0, 0, 0, 0))
    ground = tiles["ground_buildable--base"]
    layout = {(0, 2): "shore--mask_01", (1, 2): "shore--mask_03"}
    roads = {(2, 1): "road_basic--mask_12", (2, 2): "road_basic--mask_05"}
    for y in range(3):
        for x in range(3):
            scene.paste(tiles[layout.get((x, y), "ground_buildable--base")] if (x, y) in layout else ground, (x * 128, y * 128))
    for (x, y), asset in roads.items():
        scene.alpha_composite(tiles[asset], (x * 128, y * 128))
    scene.alpha_composite(tiles["quest_board--base"], (128, 128 - 64))
    out = scene.resize((256, 256), Image.Resampling.LANCZOS)
    mask = Image.new("L", (256 * art.SS, 256 * art.SS), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, 256 * art.SS - 1, 256 * art.SS - 1], radius=32 * art.SS, fill=255)
    out.putalpha(mask.resize((256, 256), Image.Resampling.BOX))
    return out


def render_theme(theme: str, ids: list[tuple[str, str]]) -> dict[str, Image.Image]:
    cache = {"water": art.water_texture(theme), "ground": art.ground_texture(theme), "bank": art.bank_texture(theme)}
    road_tex = art.road_textures(theme)
    images: dict[str, Image.Image] = {}
    for group, asset_id in ids:
        if asset_id == "ground_buildable--base":
            images[asset_id] = art.reduce(cache["ground"], (128, 128))
        elif asset_id == "water--base":
            images[asset_id] = art.reduce(cache["water"], (128, 128))
        elif group == "shore_masks":
            images[asset_id] = art.shore_tile(theme, mask_of(asset_id), cache)
        elif group == "road_masks":
            images[asset_id] = art.road_tile(theme, mask_of(asset_id), road_tex)
        elif asset_id == "quest_board--base":
            images[asset_id] = art.quest_board(theme)
        elif asset_id == "wood--icon":
            images[asset_id] = art.wood_icon(theme)
    images["theme_thumbnail--base"] = thumbnail(theme, images)
    return images


def encode(img: Image.Image, alpha: bool) -> bytes:
    buf = io.BytesIO()
    if alpha:
        img.convert("RGBA").save(buf, "WEBP", quality=WEBP_QUALITY, method=6, alpha_quality=100)
    else:
        img.convert("RGB").save(buf, "WEBP", quality=WEBP_QUALITY, method=6)
    return buf.getvalue()


